/**
 * Retourne la liste des communes correspondant au code ou au nom de la wilaya
 */
export function getCommunesByWilaya(wilayaCodeOrName: string | number): string[] {
    if (!wilayaCodeOrName) return [];
    
    // Si c'est un numéro ou string numérique
    const num = Number(wilayaCodeOrName);
    if (!isNaN(num) && ALGERIA_COMMUNES[num]) {
        return ALGERIA_COMMUNES[num];
    }

    // Si c'est un nom de wilaya
    const str = String(wilayaCodeOrName).trim().toLowerCase();
    const normalize = (s: string) =>
        s.toLowerCase()
         .normalize("NFD")
         .replace(/[\u0300-\u036f]/g, "")
         .replace(/[^a-z0-9]/g, "");

    const normTarget = normalize(str);

    // Dictionnaire des noms de wilaya normalisés vers leur code
    const WILAYA_NAMES: Record<string, number> = {
        adrar: 1, chlef: 2, laghouat: 3, oumelbouaghi: 4, batna: 5,
        bejaia: 6, biskra: 7, bechar: 8, blida: 9, bouira: 10,
        tamanrasset: 11, tebessa: 12, tlemcen: 13, tiaret: 14, tiziouzou: 15,
        alger: 16, djelfa: 17, jijel: 18, setif: 19, saida: 20,
        skikda: 21, sidibelabbes: 22, annaba: 23, guelma: 24, constantine: 25,
        medea: 26, mostaganem: 27, msila: 28, mascara: 29, ouargla: 30,
        oran: 31, elbayadh: 32, illizi: 33, bordjbouarreridj: 34, boumerdes: 35,
        eltarf: 36, tindouf: 37, tissemsilt: 38, eloued: 39, khenchela: 40,
        soukahras: 41, tipaza: 42, mila: 43, aindefla: 44, naama: 45,
        aintemouchent: 46, ghardaia: 47, relizane: 48, timimoun: 49,
        bordjbadjimokhtar: 50, ouleddjellal: 51, beniabbes: 52, insalah: 53,
        inguezzam: 54, touggourt: 55, djanet: 56, elmghair: 57, elmeniaa: 58,
        elmenia: 58
    };

    const code = WILAYA_NAMES[normTarget];
    if (code && ALGERIA_COMMUNES[code]) {
        return ALGERIA_COMMUNES[code];
    }

    // Recherche partielle
    for (const [k, v] of Object.entries(WILAYA_NAMES)) {
        if (normTarget.includes(k) || k.includes(normTarget)) {
            return ALGERIA_COMMUNES[v] || [];
        }
    }

    return [];
}
